#!/usr/bin/env node

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const ENTRIES_DIR = path.join(ROOT, 'components', 'content-blocks', 'entries');
const OUTPUT = path.join(ROOT, 'components', 'content-blocks', 'registry.generated.ts');
const CHECK_ONLY = process.argv.includes('--check');
const unknownOptions = process.argv.slice(2).filter((option) => option !== '--check');

if (unknownOptions.length > 0) {
  throw new Error(`Unknown option${unknownOptions.length === 1 ? '' : 's'}: ${unknownOptions.join(', ')}`);
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.tsx')) out.push(full);
  }
  return out;
}

const entries = walk(ENTRIES_DIR)
  .map((file) => {
    const relative = path.relative(ENTRIES_DIR, file).replace(/\\/g, '/').replace(/\.tsx$/, '');
    return {
      id: relative,
      importPath: `./entries/${relative}`,
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const ids = entries.map(({ id }) => JSON.stringify(id)).join(' | ') || 'string';
const imports = entries
  .map(({ id, importPath }) => `  ${JSON.stringify(id)}: dynamic(() => import(${JSON.stringify(importPath)})),`)
  .join('\n');
const idList = entries.map(({ id }) => `  ${JSON.stringify(id)},`).join('\n');

const source = `/* This file is generated by scripts/generate-content-block-registry.cjs. */
import dynamic from 'next/dynamic';
import type { ComponentType } from 'react';
import type { InteractiveContentBlockProps } from './InteractiveContentBlock';

export type ContentBlockComponent = ComponentType<Pick<InteractiveContentBlockProps, 'dataFile'>>;
export type ContentBlockId = ${ids};

export const contentBlockRegistry: Partial<Record<string, ContentBlockComponent>> = {
${imports}
};

export const contentBlockIds: ContentBlockId[] = [
${idList}
];
`;

if (CHECK_ONLY) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== source) {
    console.error(
      `${path.relative(ROOT, OUTPUT)} is stale. Run pnpm generate:content-blocks and commit the result.`
    );
    process.exit(1);
  }
  console.log(`Content block registry is current (${entries.length} blocks).`);
} else {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, source);
  console.log(`Generated ${path.relative(ROOT, OUTPUT)} with ${entries.length} block(s).`);
}
